-- Talent onboarding. Unlike a tool submission there is no approval queue: the wizard creates the account
-- and its profile outright, so this is normalised rather than parked in JSONB - the talent directory
-- filters on skills, workplace, location, employment type and languages.
CREATE TABLE talent_profile (
    account_id BIGINT PRIMARY KEY REFERENCES account(id),
    full_name VARCHAR(200) NOT NULL,
    country VARCHAR NOT NULL, -- todo: reference table, the front end already ships a fixed COUNTRIES list
    title VARCHAR(200) NOT NULL,
    short_description VARCHAR(180),  -- SHORT_DESCRIPTION_MAX_LENGTH
    summary VARCHAR(1000) NOT NULL,  -- SUMMARY_MAX_LENGTH
    resume_file_name VARCHAR,
    work_location VARCHAR NOT NULL REFERENCES location(name),
    work_relocation VARCHAR NOT NULL,
    work_workplace VARCHAR NOT NULL,
    work_employment_type VARCHAR NOT NULL,
    link_linkedin VARCHAR,
    link_github VARCHAR,
    link_portfolio VARCHAR,
    link_other VARCHAR,
    created_at TIMESTAMPTZ NOT NULL default NOW()
);

CREATE TABLE talent_skill (
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    skill VARCHAR NOT NULL REFERENCES skill(name),
    CONSTRAINT talent_skill_unique UNIQUE (account_id, skill)
);

CREATE INDEX talent_skill_skill_idx ON talent_skill (skill);

CREATE TABLE talent_language (
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    language VARCHAR NOT NULL REFERENCES language(name),
    proficiency VARCHAR NOT NULL,
    display_order INT NOT NULL default 0,
    CONSTRAINT talent_language_unique UNIQUE (account_id, language)
);

-- display_order preserves the order the rows were entered in the wizard; the ids the form carries
-- ("exp-1", "edu-1") are React keys regenerated every session and are deliberately not stored.
CREATE TABLE talent_experience (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    display_order INT NOT NULL default 0,
    company VARCHAR NOT NULL,
    position VARCHAR NOT NULL,
    location VARCHAR REFERENCES location(name),
    workplace VARCHAR,
    period VARCHAR,
    description VARCHAR
);

CREATE TABLE talent_education (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    display_order INT NOT NULL default 0,
    institution VARCHAR NOT NULL,
    degree VARCHAR NOT NULL,
    field VARCHAR NOT NULL,
    graduation_year VARCHAR(4) NOT NULL,
    location VARCHAR NOT NULL REFERENCES location(name)
);

CREATE TABLE talent_certification (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    display_order INT NOT NULL default 0,
    name VARCHAR NOT NULL,
    organization VARCHAR NOT NULL,
    year VARCHAR(4)
);

CREATE TABLE talent_course (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    display_order INT NOT NULL default 0,
    name VARCHAR NOT NULL,
    provider VARCHAR,
    focus VARCHAR,
    completion_year VARCHAR(4)
);

CREATE TABLE talent_project (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL REFERENCES talent_profile(account_id),
    display_order INT NOT NULL default 0,
    title VARCHAR NOT NULL,
    category VARCHAR,
    year VARCHAR(4),
    description VARCHAR
);
