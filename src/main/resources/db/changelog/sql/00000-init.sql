CREATE TABLE role
(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) UNIQUE NOT NULL,
    description VARCHAR
);

CREATE TABLE permission
(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) UNIQUE NOT NULL,
    description VARCHAR
);

CREATE TABLE role_permission
(
    role BIGINT REFERENCES role (id) ON DELETE CASCADE,
    permission BIGINT REFERENCES permission (id) ON DELETE CASCADE,
    CONSTRAINT roles_permission_unique UNIQUE (role, permission)
);

CREATE TABLE data_permission
(
   permission_name VARCHAR REFERENCES permission (name) ON DELETE CASCADE,
   data_key VARCHAR NOT NULL,
   scope VARCHAR NOT NULL,
   CONSTRAINT data_permission_unique UNIQUE(permission_name, data_key)
);

